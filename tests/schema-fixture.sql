CREATE OR REPLACE FUNCTION public.admin_decide_money_request(p_id uuid, p_approve boolean)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare r public.money_requests%rowtype; t_id uuid;
begin
 if not public.is_admin() then raise exception 'Admin only'; end if;
 select * into r from public.money_requests where id=p_id for update;
 if not found or r.status <> 'pending' then raise exception 'Request unavailable'; end if;
 update public.money_requests set status=case when p_approve then 'approved' else 'rejected' end where id=p_id;
 if p_approve then
   insert into public.transfers(project_id, supervisor_id, request_id, amount)
   values(r.project_id,r.supervisor_id,r.id,r.amount) returning id into t_id;
 end if;
 return t_id;
end $function$;
