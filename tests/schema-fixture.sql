CREATE OR REPLACE FUNCTION public.rls_auto_enable()
 RETURNS event_trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  cmd record;
  tbl name;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        SELECT c.relname INTO tbl FROM pg_catalog.pg_class c WHERE c.oid = cmd.objid;
        EXECUTE format('alter table if exists %I.%I enable row level security', cmd.schema_name, tbl);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;
CREATE OR REPLACE FUNCTION public.admin_decide_equipment(p_id uuid, p_approve boolean)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  r public.equipment_requests%rowtype;
  current_qty integer;
  outstanding integer;
begin
  if not public.is_admin() then raise exception 'Admin only'; end if;
  select * into r from public.equipment_requests where id=p_id for update;
  if not found or r.status <> 'pending' then
    raise exception 'Equipment request unavailable';
  end if;
  if p_approve then
    if r.inventory_id is null then raise exception 'Inventory item required'; end if;
    -- Lock the inventory row, serializing issues and returns for this item.
    select quantity into current_qty from public.inventory
      where id=r.inventory_id for update;
    if not found then raise exception 'Inventory unavailable'; end if;
    if r.action='issue' then
      if current_qty < r.quantity then raise exception 'Insufficient stock'; end if;
      update public.inventory set quantity=quantity-r.quantity
        where id=r.inventory_id;
    elsif r.action='return' then
      select coalesce(sum(case when action='issue' then quantity else -quantity end),0)::integer
      into outstanding from public.inventory_movements
      where project_id=r.project_id and inventory_id=r.inventory_id;
      if outstanding < r.quantity then
        raise exception 'Return exceeds project issued stock';
      end if;
      update public.inventory set quantity=quantity+r.quantity
        where id=r.inventory_id;
    else
      raise exception 'Unknown equipment action';
    end if;
    insert into public.inventory_movements(
      request_id,project_id,inventory_id,action,quantity)
    values(r.id,r.project_id,r.inventory_id,r.action,r.quantity);
  end if;
  update public.equipment_requests
    set status=case when p_approve then 'accepted' else 'rejected' end
    where id=p_id;
end $function$;
