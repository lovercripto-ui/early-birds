CREATE OR REPLACE FUNCTION public.submit_attendance(p_project uuid, p_event text, p_recorded_at timestamp with time zone, p_lat double precision, p_lng double precision, p_accuracy_m double precision, p_client_event_id uuid, p_offline boolean DEFAULT false)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_user uuid := (select auth.uid());
  v_site_lat double precision;
  v_site_lng double precision;
  v_distance double precision;
  v_id uuid;
  v_existing public.checkins%rowtype;
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  if p_event not in ('in','out') or p_event is null then raise exception 'Invalid attendance event'; end if;
  if p_client_event_id is null then raise exception 'Event identifier required'; end if;
  if p_recorded_at is null then raise exception 'Timestamp required'; end if;
  -- Idempotency is checked before the sync-age/project-status restrictions:
  -- a successful earlier submission must remain replayable after closure.
  select * into v_existing from public.checkins
    where client_event_id = p_client_event_id;
  if found then
    if v_existing.supervisor_id is distinct from v_user
       or v_existing.project_id is distinct from p_project
       or v_existing.event_type is distinct from p_event
       or v_existing.recorded_at is distinct from p_recorded_at
       or v_existing.lat is distinct from p_lat
       or v_existing.lng is distinct from p_lng
       or v_existing.accuracy_m is distinct from p_accuracy_m
       or v_existing.offline_record is distinct from p_offline then
      raise exception 'Attendance event identifier conflict';
    end if;
    return v_existing.id;
  end if;
  if p_recorded_at > now() + interval '5 minutes'
     or p_recorded_at < now() - interval '7 days' then
    raise exception 'Timestamp outside allowed sync window';
  end if;
  if p_lat is null or p_lng is null or p_lat not between -90 and 90
     or p_lng not between -180 and 180 then raise exception 'Invalid coordinates'; end if;
  if p_accuracy_m is null or p_accuracy_m < 0 or p_accuracy_m > 100
     then raise exception 'Location accuracy too low'; end if;
  if not public.assigned_to(p_project) then raise exception 'Not assigned to project'; end if;
  select site_lat,site_lng into v_site_lat,v_site_lng
  from public.projects where id=p_project and status='ongoing';
  if not found or v_site_lat is null or v_site_lng is null
     then raise exception 'Project site coordinates not configured'; end if;
  -- Haversine distance in meters; clamp floating-point rounding to [-1,1].
  v_distance := 6371000 * 2 * asin(sqrt(least(1.0, greatest(0.0,
    power(sin(radians(p_lat-v_site_lat)/2),2) +
    cos(radians(v_site_lat))*cos(radians(p_lat))*
    power(sin(radians(p_lng-v_site_lng)/2),2)))));
  if v_distance > 1000 then raise exception 'Outside 1 km site radius'; end if;
  insert into public.checkins(project_id,supervisor_id,event_type,recorded_at,
      lat,lng,accuracy_m,offline_record,verification_status,client_event_id)
  values(p_project,v_user,p_event,p_recorded_at,p_lat,p_lng,p_accuracy_m,
      p_offline,case when p_offline then 'offline_unverified' else 'location_checked' end,
      p_client_event_id)
  on conflict(client_event_id) do nothing returning id into v_id;
  if v_id is null then
    -- A concurrent insert won the unique-key race. Never silently accept a
    -- different payload simply because it reused the same UUID.
    select * into v_existing from public.checkins
      where client_event_id=p_client_event_id;
    if not found
       or v_existing.supervisor_id is distinct from v_user
       or v_existing.project_id is distinct from p_project
       or v_existing.event_type is distinct from p_event
       or v_existing.recorded_at is distinct from p_recorded_at
       or v_existing.lat is distinct from p_lat
       or v_existing.lng is distinct from p_lng
       or v_existing.accuracy_m is distinct from p_accuracy_m
       or v_existing.offline_record is distinct from p_offline then
      raise exception 'Attendance event identifier conflict';
    end if;
    v_id := v_existing.id;
  end if;
  return v_id;
end $function$;
CREATE OR REPLACE FUNCTION public.admin_lookup_attendance(p_client_event_id uuid)
 RETURNS TABLE(id uuid, client_event_id uuid, project_id uuid, supervisor_id uuid, event_type text, recorded_at timestamp with time zone, offline_record boolean, verification_status text)
 LANGUAGE plpgsql
 STABLE
 SET search_path TO ''
AS $function$
begin
  if (select auth.uid()) is null or not (select public.is_admin()) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if p_client_event_id is null then
    raise exception 'Event ID required' using errcode = '22023';
  end if;
  return query
    select c.id, c.client_event_id, c.project_id, c.supervisor_id,
           c.event_type, c.recorded_at, c.offline_record, c.verification_status
    from public.checkins as c
    where c.client_event_id = p_client_event_id
    limit 1;
end;
$function$;
CREATE OR REPLACE FUNCTION public.register_company_workspace(p_company_name text, p_admin_name text, p_address text DEFAULT NULL::text, p_contact_number text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
 v_user uuid := (select auth.uid());
 v_company uuid;
begin
 if v_user is null then
   raise exception 'Authentication required' using errcode='28000';
 end if;
 if not exists (
   select 1 from auth.users u where u.id=v_user
     and u.email_confirmed_at is not null
     and u.is_anonymous is not true
 ) then
   raise exception 'Verified email account required' using errcode='28000';
 end if;
 if p_company_name is null or length(btrim(p_company_name)) not between 2 and 160
    or p_admin_name is null or length(btrim(p_admin_name)) not between 2 and 120 then
   raise exception 'Invalid company or admin name' using errcode='22023';
 end if;
 -- A user can belong to only one company; the profile PK enforces this under concurrency.
 if exists (select 1 from public.profiles where id=v_user) then
   raise exception 'User already has a workspace' using errcode='23505';
 end if;
 insert into public.companies(name,address,contact_number)
 values(btrim(p_company_name),nullif(btrim(p_address),''),nullif(btrim(p_contact_number),''))
 returning id into v_company;
 insert into public.profiles(id,display_name,role,company_id)
 values(v_user,btrim(p_admin_name),'admin'::public.app_role,v_company);
 return v_company;
end;
$function$;
